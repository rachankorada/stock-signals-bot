import { Navigate, NavLink, Route, Routes } from "react-router-dom";
import { useApp } from "./live";
import Dashboard from "./pages/Dashboard";
import Login from "./pages/Login";
import SettingsPage from "./pages/Settings";
import SignalDetail from "./pages/SignalDetail";
import Ticker from "./pages/Ticker";
import TrackRecord from "./pages/TrackRecord";
import Watchlist from "./pages/Watchlist";

const NAV = [
  { to: "/", label: "Signals" },
  { to: "/watchlist", label: "Watchlist" },
  { to: "/record", label: "Track record" },
  { to: "/settings", label: "Settings" },
];

export default function App() {
  const { user, loading, connected } = useApp();
  if (loading) return <div className="center muted">Loading…</div>;
  if (!user) {
    return (
      <Routes>
        <Route path="/login" element={<Login />} />
        <Route path="*" element={<Navigate to="/login" replace />} />
      </Routes>
    );
  }
  return (
    <div className="shell">
      <header className="topbar">
        <NavLink to="/" className="brand">
          Stock Analyzer
        </NavLink>
        <nav>
          {NAV.map((n) => (
            <NavLink key={n.to} to={n.to} end={n.to === "/"}>
              {n.label}
            </NavLink>
          ))}
        </nav>
        <span className={`dot ${connected ? "on" : "off"}`} title={connected ? "Live alerts connected" : "Reconnecting to live alerts"} />
      </header>
      <main>
        <Routes>
          <Route path="/" element={<Dashboard />} />
          <Route path="/watchlist" element={<Watchlist />} />
          <Route path="/ticker/:symbol" element={<Ticker />} />
          <Route path="/signal/:id" element={<SignalDetail />} />
          <Route path="/record" element={<TrackRecord />} />
          <Route path="/settings" element={<SettingsPage />} />
          <Route path="*" element={<Navigate to="/" replace />} />
        </Routes>
      </main>
      <footer>
        Signals are generated by an automated model for information only. They are not financial advice, and past
        results do not guarantee future results. Trading involves risk of loss.
      </footer>
    </div>
  );
}
